        writer.WriteLine("}");
        writer.WriteLine("static void ct_thread_publish_ready(void) { if (ct_atomic_load_relaxed(&ct_runtime_phase) != CT_RUNTIME_INITIALIZING) ct_fail(\"CTT0002\", \"<runtime-init>\", 0); ct_atomic_store_release(&ct_runtime_phase, CT_RUNTIME_READY); }");
        writer.WriteLine("void ct_thread_attach(void)");
        writer.WriteLine("{");
        writer.WriteLine("    if (ct_thread_current() != NULL || ct_atomic_load_acquire(&ct_runtime_phase) != CT_RUNTIME_READY) ct_fail(\"CTT0002\", \"<thread-attach>\", 0);");
        writer.WriteLine("    ct_thread_state* state = (ct_thread_state*)calloc(1u, sizeof(ct_thread_state));");
        writer.WriteLine("    if (state == NULL) ct_fail(\"CTM0001\", \"<thread-attach>\", 0);");
        writer.WriteLine("    state->HeapAllocated = true;");
        writer.WriteLine("    (void)ct_atomic_fetch_add_relaxed(&ct_attached_thread_count, 1u);");
        writer.WriteLine("    if (ct_atomic_load_acquire(&ct_runtime_phase) != CT_RUNTIME_READY) { (void)ct_atomic_fetch_sub_release(&ct_attached_thread_count, 1u); free(state); ct_fail(\"CTT0002\", \"<thread-attach>\", 0); }");
        writer.WriteLine("    ct_thread_set_current(state);");
        writer.WriteLine("}");
        writer.WriteLine("void ct_thread_detach(void)");
        writer.WriteLine("{");
        writer.WriteLine("    ct_thread_state* state = ct_thread_current();");
        writer.WriteLine("    if (state == NULL || state->CleanupTop != NULL || state->ReleaseHead != NULL || state->ReleaseDraining) ct_fail(\"CTT0002\", \"<thread-detach>\", 0);");
        if (_usesExceptions)
            writer.WriteLine("    if (state->ExceptionTop != NULL || state->CurrentException != NULL) ct_fail(\"CTT0002\", \"<thread-detach>\", 0);");
        writer.WriteLine("    bool heap_allocated = state->HeapAllocated;");
        writer.WriteLine("    ct_thread_set_current(NULL);");
        writer.WriteLine("    if (ct_atomic_fetch_sub_release(&ct_attached_thread_count, 1u) == 0u) ct_fail(\"CTT0002\", \"<thread-detach>\", 0);");
        writer.WriteLine("    if (heap_allocated) free(state);");
        writer.WriteLine("}");
        writer.WriteLine("static void ct_thread_begin_shutdown(void)");
        writer.WriteLine("{");
        writer.WriteLine("    uint32_t expected = CT_RUNTIME_READY;");
        writer.WriteLine("    if (!ct_atomic_compare_exchange_release(&ct_runtime_phase, &expected, CT_RUNTIME_SHUTTING_DOWN) || ct_atomic_load_acquire(&ct_attached_thread_count) != 1u) ct_fail(\"CTT0002\", \"<runtime-shutdown>\", 0);");
        writer.WriteLine("}");
        writer.WriteLine("void ct_runtime_initialize(const ct_runtime_config* config)");
        writer.WriteLine("{");
        writer.WriteLine("    if (ct_atomic_load_acquire(&ct_runtime_phase) != CT_RUNTIME_UNINITIALIZED) ct_fail(\"CTT0002\", \"<runtime-init>\", 0);");
        writer.WriteLine("    if (config != NULL) { if (config->Size != sizeof(ct_runtime_config)) ct_fail(\"CTT0003\", \"<runtime-init>\", 0); ct_installed_panic_handler = config->PanicHandler; ct_installed_panic_context = config->PanicContext; }");
        writer.WriteLine("    ct_thread_attach_primary(&ct_primary_thread_state);");
        writer.WriteLine("    if (ct_program_module.AbiVersion != CTILDE_RUNTIME_ABI_VERSION) ct_fail(\"CTT0003\", \"<runtime-init>\", 0);");
        writer.WriteLine("    ct_runtime_faults_init();");
        if (_usesExceptions)
        {
            writer.WriteLine("    jmp_buf ct_init_jump;");
            writer.WriteLine("    ct_exception_frame ct_init_frame = { &ct_init_jump, ct_primary_thread_state.ExceptionTop, ct_primary_thread_state.CleanupTop };");
            writer.WriteLine("    ct_primary_thread_state.ExceptionTop = &ct_init_frame;");
            writer.WriteLine("    if (setjmp(ct_init_jump) != 0)");
            writer.WriteLine("    {");
            writer.WriteLine("        ct_object* exception = ct_primary_thread_state.CurrentException;");
            writer.WriteLine("        ct_primary_thread_state.CurrentException = NULL;");
            writer.WriteLine("        ct_primary_thread_state.ExceptionTop = ct_init_frame.Previous;");
            writer.WriteLine("        ct_program_module.Finalize();");
            writer.WriteLine("        ct_unhandled_exception(exception);");
            writer.WriteLine("    }");
            writer.WriteLine("    ct_program_module.Initialize();");
            writer.WriteLine("    ct_primary_thread_state.ExceptionTop = ct_init_frame.Previous;");
        }
        else
            writer.WriteLine("    ct_program_module.Initialize();");
        writer.WriteLine("    ct_thread_publish_ready();");
        writer.WriteLine("}");
        writer.WriteLine("void ct_runtime_shutdown(void)");
        writer.WriteLine("{");
        writer.WriteLine("    if (ct_thread_current() != &ct_primary_thread_state) ct_fail(\"CTT0002\", \"<runtime-shutdown>\", 0);");
        writer.WriteLine("    ct_thread_begin_shutdown();");
        writer.WriteLine("    ct_program_module.Finalize();");
        writer.WriteLine("    ct_thread_detach();");
        writer.WriteLine("}");
        writer.WriteLine("#if defined(CT_MEMORY_DIAGNOSTICS)");
        writer.WriteLine("uint32_t ct_memory_diagnostic_attached_threads(void) { return ct_atomic_load_relaxed(&ct_attached_thread_count); }");
        writer.WriteLine("#endif");
    }

    private void EmitBoxLayouts(CWriter writer)
    {
        foreach (var type in BoxedTypes)
            writer.WriteLine($"typedef struct {BoxName(type)} {{ ct_object Object; {CDeclaration(type, "Value")}; }} {BoxName(type)};");
        if (_boxedTypes.Count > 0)
            writer.WriteLine();
    }

    private void EmitGlobals(CWriter writer)
    {
        foreach (var field in EmittedTypes.SelectMany(type => type.Fields).Where(field => field.IsStatic && field.Name != "<underlying>"))
        {
            writer.WriteLine($"static {CDeclaration(field.Type, field.CName)} = {DefaultValue(field.Type)};");
        }
        if (EmittedTypes.SelectMany(type => type.Fields).Any(field => field.IsStatic && field.Name != "<underlying>"))
            writer.WriteLine();
    }

    private void EmitPrototypes(CWriter writer)
    {
        var emittedExternalSymbols = new HashSet<string>(StringComparer.Ordinal);
        foreach (var type in EmittedTypes.Where(type => type.Kind is not DeclaredTypeKind.Enum and not DeclaredTypeKind.Opaque))
        {
            foreach (var constructor in type.Constructors)
            {
                if (!_reachableMethods.Contains(constructor))
                    continue;
                writer.WriteLine(MethodSignature(constructor, prototype: true));
                if (type.Kind == DeclaredTypeKind.Class)
                {
                    var parameters = new[] { $"{NameMangler.Type(type)}* ct_self" }
                        .Concat(constructor.Parameters.Select(parameter => CParameterDeclaration(parameter, NameMangler.Identifier(parameter.Name))));
                    writer.WriteLine($"static void {ConstructorInitializerName(constructor)}({string.Join(", ", parameters)});");
                }
            }
            foreach (var method in type.Methods)
            {
                if (IsEspIdf && method.ExternName == "ct_environment_exit")
                    continue;
                if (method.ExternName is not null && !emittedExternalSymbols.Add(method.ExternName))
                    continue;
                if (method.ExternName is null && !_reachableMethods.Contains(method))
                    continue;
                writer.WriteLine(MethodSignature(method, prototype: true));
            }
            foreach (var property in type.Properties)
            {
                if (!_reachableProperties.Contains(property))
                    continue;
                var self = property.IsStatic ? string.Empty : $"{InstanceStorageType(type)}* ct_self";
                if (property.Getter is not null)
                    writer.WriteLine("static " + CFunctionDeclaration(property.Type, NameMangler.Getter(property), self.Length == 0 ? [] : [self]) + ";");
                if (property.Setter is not null)
                {
                    var parameters = self.Length == 0
                        ? new[] { CDeclaration(property.Type, NameMangler.Identifier("value")) }
                        : new[] { self, CDeclaration(property.Type, NameMangler.Identifier("value")) };
                    writer.WriteLine("static " + CFunctionDeclaration(CType.Void, NameMangler.Setter(property), parameters) + ";");
                }
            }
        }
    }

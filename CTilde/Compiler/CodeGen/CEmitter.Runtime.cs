        writer.WriteLine("void ct_debug_method_leave(void* value) { ct_debug_method_frame* frame = (ct_debug_method_frame*)value; if (!frame->Active) return; ct_thread_state* state = (ct_thread_state*)frame->State; frame->Active = false; if (state == NULL || state->DebugDepth == 0u || state->DebugFrameTop != frame) ct_fail(\"CTM0003\", \"<debug-depth>\", 0); state->DebugFrameTop = frame->Previous; --state->DebugDepth; }");
        writer.WriteLine("CT_DEBUG_NOINLINE void ct_debug_site(uint32_t site)");
        writer.WriteLine("{");
        writer.WriteLine("    ct_thread_state* state = ct_thread_require_attached();");
        writer.WriteLine("    state->DebugCurrentSite = site;");
        writer.WriteLine("    if (ct_debug_control.SessionActive == 0u || site >= ct_debug_control.SiteCount) return;");
        writer.WriteLine("    bool stop = (ct_debug_control.Enabled[site / 32u] & (UINT32_C(1) << (site % 32u))) != 0u;");
        writer.WriteLine("    if (!stop && ct_debug_control.SelectedThread == (uintptr_t)(void*)state) {");
        writer.WriteLine("        if (ct_debug_control.StepMode == 1u) stop = true;");
        writer.WriteLine("        else if (ct_debug_control.StepMode == 2u && state->DebugDepth <= ct_debug_control.StepDepth) stop = true;");
        writer.WriteLine("        else if (ct_debug_control.StepMode == 3u && state->DebugDepth < ct_debug_control.StepDepth) stop = true;");
        writer.WriteLine("    }");
        writer.WriteLine("    if (!stop) return;");
        writer.WriteLine("    ct_debug_stop_acquire(); ct_debug_control.StepMode = 0u; ct_debug_control.CurrentThread = (uintptr_t)(void*)state; ct_debug_control.CurrentActivation = state->DebugFrameTop == NULL ? 0u : state->DebugFrameTop->Activation; ct_debug_control.CurrentSite = site; ct_debug_control.CurrentReason = CT_DEBUG_REASON_SITE; ct_debug_control.CurrentObject = 0u; ct_debug_control.CurrentValue = state->DebugDepth; ct_debug_control.CurrentCode = 0u; ct_debug_control.CurrentFile = 0u; ct_debug_control.CurrentLine = 0;");
        writer.WriteLine($"    ct_debug_refresh_runtime_summary(); {(IsQemu ? "ct_debug_qemu_trap" : "ct_debug_trap")}(); ct_debug_stop_release();");
        writer.WriteLine("}");
        writer.WriteLine("static void ct_debug_runtime_event(uint32_t reason, uint32_t mask, ct_object* object, uint32_t value, const char* code, const char* file, int32_t line)");
        writer.WriteLine("{");
        writer.WriteLine("    if (ct_debug_control.SessionActive == 0u || (ct_debug_control.EventMask & mask) == 0u) return;");
        writer.WriteLine($"    ct_thread_state* state = ct_thread_current(); ct_debug_stop_acquire(); ct_debug_control.CurrentThread = (uintptr_t)(void*)state; ct_debug_control.CurrentActivation = state == NULL || state->DebugFrameTop == NULL ? 0u : state->DebugFrameTop->Activation; ct_debug_control.CurrentSite = state == NULL ? UINT32_MAX : state->DebugCurrentSite; ct_debug_control.CurrentReason = reason; ct_debug_control.CurrentObject = (uintptr_t)(void*)object; ct_debug_control.CurrentValue = value; ct_debug_control.CurrentCode = (uintptr_t)(const void*)code; ct_debug_control.CurrentFile = (uintptr_t)(const void*)file; ct_debug_control.CurrentLine = line; ct_debug_refresh_runtime_summary(); {(IsQemu ? "ct_debug_qemu_trap" : "ct_debug_trap")}(); ct_debug_stop_release();");
        writer.WriteLine("}");
        writer.WriteLine("CT_DEBUG_NOINLINE void ct_debug_throw_hook(ct_object* exception, const char* code, const char* file, int line, uint32_t unhandled) { ct_debug_probe_sink = (uintptr_t)(void*)exception ^ (uintptr_t)(unsigned int)line ^ (uintptr_t)unhandled; ct_debug_runtime_event(CT_DEBUG_REASON_THROW, unhandled != 0u ? CT_DEBUG_EVENT_UNHANDLED : CT_DEBUG_EVENT_THROW, exception, unhandled, code, file, line); }");
        writer.WriteLine("CT_DEBUG_NOINLINE void ct_debug_fatal_hook(const char* code, const char* file, int line) { ct_debug_probe_sink = (uintptr_t)(unsigned int)line; ct_debug_runtime_event(CT_DEBUG_REASON_FATAL, CT_DEBUG_EVENT_FATAL, NULL, 0u, code, file, line); }");
        if (EmitDebugObjects)
        {
            writer.WriteLine("static void ct_debug_object_initialized(ct_object* object) { ct_debug_allocation* allocation = ct_debug_allocation_for(object); ct_thread_state* state = ct_thread_current(); ct_atomic_store_relaxed(&allocation->LastSite, state == NULL ? UINT32_MAX : state->DebugCurrentSite); ct_debug_runtime_event(CT_DEBUG_REASON_ALLOC, CT_DEBUG_EVENT_ALLOC, object, ct_atomic_load_relaxed(&object->RefCount), NULL, NULL, 0); }");
            writer.WriteLine("static void ct_debug_arc_touch(ct_object* object) { if (object == NULL || ct_atomic_load_relaxed(&object->RefCount) == UINT32_MAX) return; ct_debug_allocation* allocation = ct_debug_allocation_for(object); ct_thread_state* state = ct_thread_current(); ct_atomic_store_relaxed(&allocation->LastSite, state == NULL ? UINT32_MAX : state->DebugCurrentSite); }");
            writer.WriteLine("static void ct_debug_report_leaks(void) { uint32_t count = ct_atomic_load_relaxed(&ct_debug_live_count); if (count == 0u) return; (void)fprintf(stderr, \"C~ debug: %\" PRIu32 \" managed object(s) remain live at shutdown\\n\", count); ct_debug_runtime_event(CT_DEBUG_REASON_LEAK, CT_DEBUG_EVENT_LEAK, ct_debug_live_head == NULL ? NULL : (ct_object*)(void*)(ct_debug_live_head + 1), count, NULL, NULL, 0); }");
        }
        if (IsEspIdf)
        {
            writer.WriteLine($"void ct_debug_startup_probe(void) {{ if (ct_debug_control.SessionActive == 0u || (ct_debug_control.EventMask & CT_DEBUG_EVENT_STARTUP) == 0u) return; ct_debug_stop_acquire(); ct_debug_control.CurrentThread = 0u; ct_debug_control.CurrentActivation = 0u; ct_debug_control.CurrentSite = UINT32_MAX; ct_debug_control.CurrentReason = CT_DEBUG_REASON_STARTUP; ct_debug_refresh_runtime_summary(); {(IsQemu ? "ct_debug_qemu_trap" : "ct_debug_trap")}(); ct_debug_stop_release(); }}");
            if (IsQemu)
                writer.WriteLine("CT_DEBUG_NOINLINE void ct_debug_qemu_ready(void) { ct_debug_probe_sink ^= (uintptr_t)2u; }");
            else
            {
                writer.WriteLine("void ct_debug_wait_for_client(void)");
                writer.WriteLine("{");
                writer.WriteLine("    int64_t start = ct_esp_timer_get_time_us();");
                writer.WriteLine("    while (ct_debug_control.StartupReleased == 0u && ct_esp_timer_get_time_us() - start < INT64_C(15000000)) ct_esp_delay_ms(UINT32_C(10));");
                writer.WriteLine("}");
            }
        }
    }

    private void EmitBoxLayouts(CWriter writer)
    {
        foreach (var type in BoxedTypes)
            writer.WriteLine($"typedef struct {BoxName(type)} {{ ct_object Object; {CDeclaration(type, "Value")}; }} {BoxName(type)};");
        if (_boxedTypes.Count > 0)
            writer.WriteLine();
    }

    private void EmitGlobals(CWriter writer)
    {
        foreach (var field in EmittedTypes.SelectMany(type => type.Fields).Where(field => field.IsStatic && field.Name != "<underlying>").OrderBy(field => field.CName, StringComparer.Ordinal))
        {
            if (field.LinkerSymbolName is not null || field.IsRegister)
                continue;
            if (field.ExternName is not null)
            {
                var qualifiers = (field.IsReadonly ? "const " : string.Empty) + (field.IsNativeVolatile ? "volatile " : string.Empty);
                writer.WriteLine($"extern {qualifiers}{CDeclaration(field.Type, field.CName)};");
                continue;
            }
            if (field.EmbeddedData is { } embedded)
            {
                var dataName = NameMangler.Artifact("ct_embed_", NameMangler.MemberIdentity(field));
                var bytes = embedded.Length == 0
                    ? "UINT8_C(0)"
                    : string.Join(", ", embedded.Select(value => $"UINT8_C(0x{value:X2})"));
                writer.WriteLine($"static const uint8_t {dataName}[{Math.Max(1, embedded.Length)}] = {{ {bytes} }};");
                writer.WriteLine($"static const {CDeclaration(field.Type, field.CName)} = {{ {dataName}, (size_t){embedded.Length} }};");
                continue;
            }
            var constInitializer = Model.ConstInitializers.GetValueOrDefault(field);
            var value = constInitializer is null
                ? field.Type.Kind is CTypeKind.Struct or CTypeKind.InlineArray ? "{0}" : DefaultValue(field.Type)
                : RenderConstData(constInitializer);
            var retention = field.IsUsed ? "CT_USED " : field.Alignment is not null ? "CT_UNUSED " : string.Empty;
            var storage = field.IsUsed ? string.Empty : "static ";
            var interruptData = IsEspIdf && field.IsInterruptData ? "DRAM_ATTR " : string.Empty;
            var sectionKind = field.IsConstInit ? NativeSectionKind.ReadOnlyData : NativeSectionKind.Data;
            var qualifier = field.IsConstInit ? "const " : string.Empty;
            writer.WriteLine($"{(field.Alignment is int alignment ? $"CT_ALIGN({alignment}) " : string.Empty)}{storage}{interruptData}{retention}{SectionAnnotation(sectionKind, field.SectionName)}{qualifier}{CDeclaration(field.Type, field.CName)} = {value};");
        }
        if (EmittedTypes.SelectMany(type => type.Fields).Any(field => field.IsStatic && field.Name != "<underlying>"))
            writer.WriteLine();
    }

    private static string RenderConstData(ConstDataValue value) => value switch
    {
        ConstDataScalar scalar => scalar.Code,
        ConstDataAggregate aggregate => $"{{ {string.Join(", ", aggregate.Elements.Select(RenderConstData))} }}",
        _ => throw new InvalidOperationException("Unknown constant-data initializer kind."),
    };

    private void EmitPrototypes(CWriter writer)
    {
        var emittedExternalSymbols = new HashSet<string>(StringComparer.Ordinal);
        foreach (var type in EmittedTypes.Where(type => type.Kind is not DeclaredTypeKind.Enum and not DeclaredTypeKind.Opaque))
        {
            foreach (var constructor in type.Constructors)
            {
                if (!_reachableMethods.Contains(constructor))
                    continue;
                writer.WriteLine(MethodSignature(constructor, prototype: true));
                if (type.Kind == DeclaredTypeKind.Class)
                {
                    var parameters = new[] { $"{NameMangler.Type(type)}* ct_self" }
                        .Concat(constructor.Parameters.Select(parameter => CParameterDeclaration(parameter, NameMangler.Identifier(parameter.Name))));
                    writer.WriteLine($"static void {ConstructorInitializerName(constructor)}({string.Join(", ", parameters)});");
                }
            }
            foreach (var method in type.Methods)
            {
                if (method.IsNaked)
                    continue;
                if (IsEspIdf && method.ExternName == "ct_environment_exit")
                    continue;
                if (method.ExternName is not null && !emittedExternalSymbols.Add(method.ExternName))
                    continue;
                if (method.ExternName is null && !_reachableMethods.Contains(method))
                    continue;
                writer.WriteLine(MethodSignature(method, prototype: true));
            }
            foreach (var property in type.Properties)
            {
                if (!_reachableProperties.Contains(property))
                    continue;
                var self = property.IsStatic ? string.Empty : $"{InstanceStorageType(type)}* ct_self";
                if (property.Getter is not null)
                {
                    var parameters = new List<string>();
                    if (self.Length != 0)
                        parameters.Add(self);
                    if (property.IndexParameter is not null)
                        parameters.Add(CParameterDeclaration(property.IndexParameter, NameMangler.Identifier(property.IndexParameter.Name)));
                    writer.WriteLine("static " + CFunctionDeclaration(property.Type, NameMangler.Getter(property), parameters) + ";");
                }
                if (property.Setter is not null)
                {
                    var parameters = new List<string>();
                    if (self.Length != 0)
                        parameters.Add(self);
                    if (property.IndexParameter is not null)
                        parameters.Add(CParameterDeclaration(property.IndexParameter, NameMangler.Identifier(property.IndexParameter.Name)));
                    parameters.Add(CDeclaration(property.Type, NameMangler.Identifier("value")));
                    writer.WriteLine("static " + CFunctionDeclaration(CType.Void, NameMangler.Setter(property), parameters) + ";");
                }
            }
        }
    }

    private void EmitRuntimeImplementationBridges(CWriter writer)
    {
        if (!IsFreestanding)
            return;
        if (Model.RuntimeImplementations.TryGetValue(RuntimeImplementationRole.Allocate, out var allocate))
            writer.WriteLine($"static void* ct_runtime_allocate_bridge(size_t size) {{ return {allocate.CName}((uintptr_t)size); }}");
        else
            writer.WriteLine("static void* ct_runtime_allocate_bridge(size_t size) { (void)size; ct_runtime_panic_bridge(\"CTM0002\", \"<runtime>\", 0); return NULL; }");
        if (Model.RuntimeImplementations.TryGetValue(RuntimeImplementationRole.Free, out var free))
            writer.WriteLine($"static void ct_runtime_free_bridge(void* value) {{ {free.CName}(value); }}");
        else
            writer.WriteLine("static void ct_runtime_free_bridge(void* value) { (void)value; ct_runtime_panic_bridge(\"CTM0002\", \"<runtime>\", 0); }");
        if (Model.RuntimeImplementations.TryGetValue(RuntimeImplementationRole.Panic, out var panic))
        {
            var info = panic.Parameters[0].Type;
            writer.WriteLine($"static void ct_runtime_panic_bridge(const char* code, const char* file, int32_t line) {{ {CTypeName(info)} info = {{ (uint8_t*)(uintptr_t)(const void*)code, (uint8_t*)(uintptr_t)(const void*)file, line }}; {panic.CName}(info); }}");
        }
        if (Model.RuntimeImplementations.Count != 0)
            writer.WriteLine();
    }

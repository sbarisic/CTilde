            writer.WriteLine("    uint32_t expected = CT_RUNTIME_READY;");
            writer.WriteLine("    if (!ct_atomic_compare_exchange_release(&ct_runtime_phase, &expected, CT_RUNTIME_SHUTTING_DOWN)) ct_fail(\"CTT0002\", \"<runtime-shutdown>\", 0);");
            writer.WriteLine("    ct_program_module.Finalize();");
            writer.WriteLine("    if (ct_primary_thread_state.CleanupTop != NULL || ct_primary_thread_state.ReleaseHead != NULL || ct_primary_thread_state.ReleaseDraining) ct_fail(\"CTT0002\", \"<runtime-shutdown>\", 0);");
            writer.WriteLine("    ct_thread_set_current(NULL);");
            writer.WriteLine("    ct_atomic_store_release(&ct_runtime_phase, CT_RUNTIME_STOPPED);");
            writer.WriteLine("}");

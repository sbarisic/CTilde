    private void EmitForwardDeclarations(CWriter writer)
    {
        foreach (var type in _functionPointerTypes.OrderBy(type => NameMangler.TypeCode(type), StringComparer.Ordinal))
        {
            var signature = type.FunctionPointer!;
            var parameters = FunctionPointerParameters(signature);
            writer.WriteLine($"typedef {CTypeName(signature.ReturnType)} (*{CTypeName(type)})({parameters});");
        }
        if (_functionPointerTypes.Count != 0)
            writer.WriteLine();
        foreach (var buffer in _nativeBufferTypes.OrderBy(NameMangler.TypeCode, StringComparer.Ordinal))
        {
            var element = CTypeName(buffer.ElementType!);
            var pointer = buffer.Kind == CTypeKind.ReadOnlyNativeBuffer ? $"const {element}*" : $"{element}*";
            writer.WriteLine($"typedef struct {CTypeName(buffer)} {{ {pointer} Data; size_t Length; }} {CTypeName(buffer)};");
        }
        if (_nativeBufferTypes.Count != 0)
            writer.WriteLine();
        foreach (var inline in _inlineArrayTypes.OrderBy(NameMangler.TypeCode, StringComparer.Ordinal))
            writer.WriteLine($"typedef struct {NameMangler.InlineArray(inline)} {NameMangler.InlineArray(inline)};");
        foreach (var type in EmittedTypes.Where(type => !type.IsStringSurface && type.Kind is not DeclaredTypeKind.Enum and not DeclaredTypeKind.Newtype and not DeclaredTypeKind.Opaque and not DeclaredTypeKind.Interface && !type.IsBitField && type.FullName != "Esp.Idf.EspError"))
            writer.WriteLine($"typedef {(type.Kind == DeclaredTypeKind.Struct && type.AggregateLayout == AggregateLayoutKind.Union ? "union" : "struct")} {NameMangler.Type(type)} {NameMangler.Type(type)};");
        foreach (var array in _arrayTypes.OrderBy(array => NameMangler.TypeCode(array), StringComparer.Ordinal))
            writer.WriteLine($"typedef struct {NameMangler.Array(array.ElementType!)} {NameMangler.Array(array.ElementType!)};");
        foreach (var type in EmittedTypes.Where(type => !type.IsStringSurface && type.Kind is DeclaredTypeKind.Class or DeclaredTypeKind.Interface or DeclaredTypeKind.Delegate).OrderBy(type => type.FullName, StringComparer.Ordinal))
            writer.WriteLine($"extern const ct_type_descriptor {DescriptorName(type)};");
        foreach (var array in _arrayTypes.OrderBy(array => NameMangler.TypeCode(array), StringComparer.Ordinal))
            writer.WriteLine($"extern const ct_type_descriptor {ArrayDescriptorName(array.ElementType!)};");
        foreach (var type in BoxedTypes)
            writer.WriteLine($"extern const ct_type_descriptor {BoxDescriptorName(type)};");
        foreach (var symbol in EmittedTypes.SelectMany(type => type.Fields).Where(field => field.LinkerSymbolName is not null)
                     .Select(field => field.LinkerSymbolName!).Distinct(StringComparer.Ordinal).OrderBy(value => value, StringComparer.Ordinal))
            writer.WriteLine($"extern unsigned char {symbol}[];");
        if (EmittedTypes.Any(type => type.Kind is not DeclaredTypeKind.Enum and not DeclaredTypeKind.Newtype and not DeclaredTypeKind.Opaque && type.FullName != "Esp.Idf.EspError") || _arrayTypes.Count > 0 || _boxedTypes.Count > 0)
            writer.WriteLine();
    }

    private void EmitTypeLayouts(CWriter writer)
    {
        foreach (var type in EmittedTypes.Where(type => type.Kind == DeclaredTypeKind.Enum))
        {
            var underlying = type.Fields.Single(field => field.Name == "<underlying>").Type;
            writer.WriteLine($"typedef {CTypeName(underlying)} {NameMangler.Type(type)};");
            foreach (var value in type.EnumValues)
                writer.WriteLine($"#define {NameMangler.Identifier(type.FullName + "." + value.Name)} (({NameMangler.Type(type)}){FormatIntegralConstant(value.Value, underlying)})");
            writer.WriteLine();
        }
        foreach (var type in EmittedTypes.Where(type => type.Kind == DeclaredTypeKind.Newtype))
        {
            writer.WriteLine(type.Alignment is int alignment
                ? $"CT_ALIGNED_TYPEDEF({CTypeName(type.UnderlyingType!)}, {NameMangler.Type(type)}, {alignment});"
                : $"typedef {CTypeName(type.UnderlyingType!)} {NameMangler.Type(type)};");
            if (type.Alignment is int requestedAlignment)
                writer.WriteLine($"static_assert(CT_ALIGNOF({NameMangler.Type(type)}) >= (size_t){requestedAlignment}, \"C~ newtype alignment mismatch\");");
            writer.WriteLine();
        }
        foreach (var type in EmittedTypes.Where(type => type.IsBitField))
        {
            writer.WriteLine($"typedef {CTypeName(type.BitFieldBackingType!)} {NameMangler.Type(type)};");
            writer.WriteLine($"static_assert(sizeof({NameMangler.Type(type)}) == sizeof({CTypeName(type.BitFieldBackingType!)}), \"C~ bitfield size mismatch\");");
            writer.WriteLine();
        }
        var emittedInlineArrays = new HashSet<CType>();
        foreach (var type in OrderLayoutTypes())
        {
            foreach (var inline in type.Fields.Where(field => !field.IsStatic).SelectMany(field => InlineArrays(field.Type)))
                EmitInlineLayout(inline);
            if (type.Kind == DeclaredTypeKind.Struct)
            {
                if (HasCpuFeature(CpuFeature.Simd128) && type.Namespace == "System.Simd" && type.Name is "F32x4" or "I32x4" or "U32x4" or "Mask32x4")
                {
                    EmitHardwareSimdLayout(type, writer);
                    writer.WriteLine();
                    continue;
                }
                AggregateLayout.EmitValueTypeDefinition(type, writer.WriteLine, CDeclaration, includeTypedef: false);
                writer.WriteLine();
                continue;
            }
            writer.WriteLine($"struct {NameMangler.Type(type)}");
            writer.WriteLine("{");
            if (type.Kind == DeclaredTypeKind.Delegate)
            {
                var parameters = string.Concat(type.DelegateParameters.Select(parameter => $", {ParameterTypeName(parameter)}"));
                writer.WriteLine("    ct_object ct_header;");
                writer.WriteLine($"    {CTypeName(type.DelegateReturnType!)} (*ct_invoke)(ct_object*{parameters});");
                writer.WriteLine("    ct_object* ct_target;");
                writer.WriteLine("};");
                writer.WriteLine();
                continue;
            }
            var fields = type.Fields.Where(field => !field.IsStatic).ToArray();
            if (type.Kind == DeclaredTypeKind.Class)
            {
                if (type.IsObject)
                    writer.WriteLine("    ct_object ct_header;");
                else if (type.BaseType is not null)
                    writer.WriteLine($"    {NameMangler.Type(type.BaseType)} ct_base;");
            }
            else if (fields.Length == 0)
                writer.WriteLine("    uint8_t ct_empty;");
            foreach (var field in fields)
                writer.WriteLine($"    {CDeclaration(field.Type, field.CName)};");
            writer.WriteLine("};");
            writer.WriteLine();
        }
        foreach (var inline in _inlineArrayTypes.OrderBy(NameMangler.TypeCode, StringComparer.Ordinal))
            EmitInlineLayout(inline);
        if (Model.Types.TryGetValue("System.Object", out var objectType) && EmittedTypes.Contains(objectType))
            writer.WriteLine($"typedef {NameMangler.Type(objectType)} ct_managed_object;");
        writer.WriteLine();

        void EmitInlineLayout(CType inline)
        {
            if (inline.InlineArrayLength <= 0)
                return;
            if (!emittedInlineArrays.Add(inline))
                return;
            foreach (var nested in InlineArrays(inline.ElementType!))
                EmitInlineLayout(nested);
            var inlineName = NameMangler.InlineArray(inline);
            writer.WriteLine($"struct {inlineName} {{ {CDeclaration(inline.ElementType!, "Data")}\x5b{inline.InlineArrayLength}\x5d; }};");
            writer.WriteLine($"static_assert(sizeof({inlineName}) == sizeof({CTypeName(inline.ElementType!)}) * (size_t){inline.InlineArrayLength}, \"C~ inline-array size mismatch\");");
            writer.WriteLine();
        }

        static IEnumerable<CType> InlineArrays(CType type)
        {
            if (type.Kind != CTypeKind.InlineArray)
                yield break;
            foreach (var nested in InlineArrays(type.ElementType!))
                yield return nested;
            yield return type;
        }
    }

    private void EmitHardwareSimdLayout(TypeSymbol type, CWriter writer)
    {
        var name = NameMangler.Type(type);
        var laneType = type.Name == "F32x4" ? "float" : "uint32_t";
        var nativeType = Architecture is CompilationArchitecture.X86 or CompilationArchitecture.X64
            ? type.Name == "F32x4" ? "__m128" : "__m128i"
            : type.Name == "F32x4" ? "float32x4_t" : "uint32x4_t";
        writer.WriteLine($"struct {name}");
        writer.WriteLine("{");
        writer.WriteLine("    union");
        writer.WriteLine("    {");
        writer.WriteLine("        struct");
        writer.WriteLine("        {");
        foreach (var field in type.Fields.Where(field => !field.IsStatic))
            writer.WriteLine($"            {laneType} {field.CAccessPath};");
        writer.WriteLine("        };");
        writer.WriteLine($"        {nativeType} ct_simd;");
        writer.WriteLine("    };");
        writer.WriteLine("};");
        writer.WriteLine($"static_assert(sizeof({name}) == 16, \"C~ SIMD layout mismatch\");");
    }

    private IEnumerable<TypeSymbol> OrderLayoutTypes()
    {
        var types = EmittedTypes.Where(type => !type.IsStringSurface && type.Kind is not DeclaredTypeKind.Enum and not DeclaredTypeKind.Newtype and not DeclaredTypeKind.Opaque and not DeclaredTypeKind.Interface && !type.IsBitField && type.FullName != "Esp.Idf.EspError").ToArray();
        var emitted = new HashSet<TypeSymbol>();
        var visiting = new HashSet<TypeSymbol>();
        foreach (var type in types)
            foreach (var result in Visit(type))
                yield return result;

        IEnumerable<TypeSymbol> Visit(TypeSymbol type)
        {
            if (emitted.Contains(type))
                yield break;
            if (!visiting.Add(type))
                yield break;
            if (type.BaseType is not null)
                foreach (var result in Visit(type.BaseType))
                    yield return result;
            foreach (var dependency in type.Fields.Where(field => !field.IsStatic).SelectMany(field => LayoutDependencies(field.Type)).Distinct())
                foreach (var result in Visit(dependency))
                    yield return result;
            visiting.Remove(type);
            if (emitted.Add(type))
                yield return type;
        }

        static IEnumerable<TypeSymbol> LayoutDependencies(CType type)
        {
            if (type.Kind == CTypeKind.Struct && type.Symbol is not null)
                yield return type.Symbol;
            if (type.Kind == CTypeKind.InlineArray)
                foreach (var nested in LayoutDependencies(type.ElementType!))
                    yield return nested;
        }
    }


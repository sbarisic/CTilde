        {
            writer.WriteLine("    ct_exception_frame* ExceptionTop;");
            writer.WriteLine("    ct_object* CurrentException;");
            writer.WriteLine("    const char* ExceptionCode;");
            writer.WriteLine("    const char* ExceptionFile;");
            writer.WriteLine("    int32_t ExceptionLine;");
        }
        writer.WriteLine("    ct_object* ReleaseHead;");
        writer.WriteLine("    bool ReleaseDraining;");
        writer.WriteLine("    bool HeapAllocated;");

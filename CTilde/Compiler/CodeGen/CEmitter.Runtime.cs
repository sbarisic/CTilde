            : "/* Generated by C~ draft 0.14 for GNU C23. Do not edit. */");
        writer.WriteLine("#include <stdbool.h>");
        writer.WriteLine("#include <stddef.h>");
        writer.WriteLine("#include <stdint.h>");
        writer.WriteLine("#include <inttypes.h>");
        writer.WriteLine("#include <stdio.h>");
        writer.WriteLine("#include <stdlib.h>");
        writer.WriteLine("#include <string.h>");
        if (_usesHostedIo)
        {
            writer.WriteLine("#include <errno.h>");
            writer.WriteLine("#if defined(_WIN32)\n#include <windows.h>\n#include <wchar.h>\n#endif");
        }
        writer.WriteLine("#include <limits.h>");
        writer.WriteLine("#include <float.h>");
        writer.WriteLine("#include <math.h>");
        writer.WriteLine("#if defined(_MSC_VER)\n#include <intrin.h>\n#endif");
        foreach (var header in EmittedTypes.Where(type => type.Kind == DeclaredTypeKind.Opaque).Select(type => type.NativeHeader!).Distinct(StringComparer.Ordinal).OrderBy(header => header, StringComparer.Ordinal))

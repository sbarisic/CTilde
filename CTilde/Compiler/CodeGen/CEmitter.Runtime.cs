using System.Globalization;
using System.Numerics;
using System.Text;

namespace CTilde;

internal sealed partial class CEmitter
{
    private void EmitPreamble(CWriter writer)
    {
        writer.WriteLine(IsEspIdf
            ? $"/* Generated by C~ draft {CompilerContract.DraftVersion} for ESP-IDF GNU C23. Do not edit. */"
            : IsFreestanding
                ? $"/* Generated by C~ draft {CompilerContract.DraftVersion} for freestanding GNU/ELF C23. Do not edit. */"
                : $"/* Generated by C~ draft {CompilerContract.DraftVersion} for GNU C23. Do not edit. */");
        writer.WriteLine("#include <stdbool.h>");
        writer.WriteLine("#include <stddef.h>");
        writer.WriteLine("#include <stdint.h>");
        writer.WriteLine("#include <inttypes.h>");
        if (HasCpuFeature(CpuFeature.Simd128))
        {
            writer.WriteLine("#define CTILDE_CPU_SIMD128 1");
            writer.WriteLine(Architecture is CompilationArchitecture.X86 or CompilationArchitecture.X64
                ? "#include <immintrin.h>"
                : "#include <arm_neon.h>");
        }
        if (!IsFreestanding)
        {
            writer.WriteLine("#include <stdio.h>");
            writer.WriteLine("#include <stdlib.h>");
            writer.WriteLine("#include <string.h>");
        }
        if (HasNativeImports)
        {
            writer.WriteLine("#if defined(_WIN32)");
            writer.WriteLine("#include <windows.h>");
            writer.WriteLine("#elif defined(__linux__)");
            writer.WriteLine("#include <dlfcn.h>");
            writer.WriteLine("#else");
            writer.WriteLine("#error \"C~ native imports are not implemented for this hosted operating system\"");
            writer.WriteLine("#endif");
        }
        if (_usesHostedIo || _usesManagedThreading)
        {
            writer.WriteLine("#include <errno.h>");
            if (_usesHostedIo)
                writer.WriteLine("#if defined(_WIN32)\n#include <windows.h>\n#include <wchar.h>\n#endif");
        }
        if (_usesMonotonicClock)
        {
            writer.WriteLine("#if defined(_WIN32)");
            writer.WriteLine("#include <windows.h>");
            writer.WriteLine("#elif defined(ESP_PLATFORM)");
            writer.WriteLine("#include <esp_timer.h>");
            writer.WriteLine("#else");
            writer.WriteLine("#include <time.h>");
            writer.WriteLine("#endif");
        }
        writer.WriteLine("#include <limits.h>");
        writer.WriteLine("#include <float.h>");
        if (!IsFreestanding)
            writer.WriteLine("#include <math.h>");
        writer.WriteLine("#if defined(_MSC_VER)\n#define CT_ALIGNOF(type) __alignof(type)\n#else\n#define CT_ALIGNOF(type) _Alignof(type)\n#endif");
        writer.WriteLine("#if defined(_MSC_VER)\n#define CT_ALIGN(n) __declspec(align(n))\n#else\n#define CT_ALIGN(n) __attribute__((aligned(n)))\n#endif");
        writer.WriteLine("#if defined(_MSC_VER)\n#define CT_ALIGNED_TYPEDEF(base, name, n) typedef __declspec(align(n)) base name\n#else\n#define CT_ALIGNED_TYPEDEF(base, name, n) typedef base name __attribute__((aligned(n)))\n#endif");
        if (!IsFreestanding)
            writer.WriteLine("#if defined(_MSC_VER)\n#include <intrin.h>\n#include <windows.h>\n#endif");
        if (_usesManagedThreading)
        {
            writer.WriteLine("#if defined(_MSC_VER)");
            writer.WriteLine("#include <process.h>");
            writer.WriteLine("#elif !defined(ESP_PLATFORM)");
            writer.WriteLine("#include <pthread.h>");
            writer.WriteLine("#include <sched.h>");
            writer.WriteLine("#include <time.h>");
            writer.WriteLine("#else");
            writer.WriteLine("#include <freertos/FreeRTOS.h>");
            writer.WriteLine("#include <freertos/task.h>");
            writer.WriteLine("#include <freertos/semphr.h>");
            writer.WriteLine("#endif");
        }
        foreach (var header in EmittedTypes.Where(type => type.Kind == DeclaredTypeKind.Opaque).Select(type => type.NativeHeader!).Distinct(StringComparer.Ordinal).OrderBy(header => header, StringComparer.Ordinal))
            writer.WriteLine($"#include <{header}>");
        if (_nativeBufferTypes.Count != 0)
            writer.WriteLine("#if defined(_MSC_VER)\n#include <malloc.h>\n#endif");
        if (_usesExceptions)
            writer.WriteLine("#include <setjmp.h>");
        if (EmitDebugInstrumentation && !IsEspIdf)
            writer.WriteLine("#include <signal.h>");
        if (IsEspIdf)
        {
            if (Model.UserTypes.SelectMany(type => type.Methods).Any(method => method.IsInterruptCode) ||
                Model.UserTypes.SelectMany(type => type.Fields).Any(field => field.IsInterruptData))
            {
                writer.WriteLine("#include <esp_attr.h>");
            }
            writer.WriteLine("#include \"ctilde_esp_shim.h\"");
            writer.WriteLine("extern void esp_restart(void) __attribute__((noreturn));");
            writer.WriteLine("extern void esp_system_abort(const char* details) __attribute__((noreturn));");
        }
        if (IsEspIdf && Model.UserTypes.SelectMany(type => type.Methods).Any(method => method.TaskStackSize is not null) && !_usesManagedThreading)
        {
            writer.WriteLine("#include <freertos/FreeRTOS.h>");
            writer.WriteLine("#include <freertos/task.h>");
        }
        if (EmitDebugInstrumentation && IsEspIdf && !IsQemu)
            writer.WriteLine("#include <esp_cpu.h>");
        if (IsFreestanding)
        {
            writer.WriteLine("static void* ct_memset(void* destination, int value, size_t count) { uint8_t* bytes = (uint8_t*)destination; for (size_t index = 0u; index < count; ++index) bytes[index] = (uint8_t)value; return destination; }");
            writer.WriteLine("static void* ct_memcpy(void* destination, const void* source, size_t count) { uint8_t* out = (uint8_t*)destination; const uint8_t* in = (const uint8_t*)source; for (size_t index = 0u; index < count; ++index) out[index] = in[index]; return destination; }");
            writer.WriteLine("static int ct_memcmp(const void* left, const void* right, size_t count) { const uint8_t* a = (const uint8_t*)left; const uint8_t* b = (const uint8_t*)right; for (size_t index = 0u; index < count; ++index) if (a[index] != b[index]) return a[index] < b[index] ? -1 : 1; return 0; }");
            writer.WriteLine("static size_t ct_strlen(const char* value) { size_t length = 0u; while (value[length] != '\\0') ++length; return length; }");
            writer.WriteLine("static void* ct_memchr(const void* value, int target, size_t count) { const uint8_t* bytes = (const uint8_t*)value; for (size_t index = 0u; index < count; ++index) if (bytes[index] == (uint8_t)target) return (void*)(uintptr_t)(const void*)(bytes + index); return NULL; }");
            writer.WriteLine("#define memset ct_memset\n#define memcpy ct_memcpy\n#define memcmp ct_memcmp\n#define strlen ct_strlen\n#define memchr ct_memchr");
        }
        writer.WriteLine();
        EmitMmioBarrier(writer);
        EmitCpuIntrinsics(writer);
        writer.WriteLine($"#define CTILDE_RUNTIME_ABI_VERSION UINT32_C({CompilerContract.RuntimeAbiVersion})");
        writer.WriteLine();
        writer.WriteLine("static_assert(CHAR_BIT == 8, \"C~ requires 8-bit bytes\");");
        writer.WriteLine("static_assert(sizeof(int32_t) == 4 && sizeof(uint32_t) == 4, \"C~ requires exact 32-bit integers\");");
        writer.WriteLine("static_assert(sizeof(int64_t) == 8 && sizeof(uint64_t) == 8, \"C~ requires exact 64-bit integers\");");
        if (_usesNativeIntegers)
        {
            writer.WriteLine("static_assert(sizeof(intptr_t) == sizeof(void*), \"C~ requires intptr_t to match pointer width\");");
            writer.WriteLine("static_assert(sizeof(uintptr_t) == sizeof(void*), \"C~ requires uintptr_t to match pointer width\");");
            writer.WriteLine("static_assert(sizeof(size_t) <= sizeof(uintptr_t), \"C~ requires nuint to represent size_t\");");
        }
        writer.WriteLine("static_assert(sizeof(float) == 4 && FLT_RADIX == 2 && FLT_MANT_DIG == 24, \"C~ requires IEEE-754 binary32 float\");");
        writer.WriteLine("static_assert(sizeof(double) == 8 && FLT_RADIX == 2 && DBL_MANT_DIG == 53, \"C~ requires IEEE-754 binary64 double\");");
        writer.WriteLine("static_assert(INT32_MIN == (-2147483647 - 1), \"C~ requires two's-complement int32_t\");");
        if (IsEspIdf)
            writer.WriteLine("static_assert(sizeof(void*) == 4, \"C~ ESP-IDF requires 32-bit pointers\");");
        writer.WriteLine();
        writer.WriteLine("#if defined(_MSC_VER)");
        writer.WriteLine("#define CT_NORETURN __declspec(noreturn)");
        writer.WriteLine("#elif defined(__GNUC__) || defined(__clang__)");
        writer.WriteLine("#define CT_NORETURN __attribute__((noreturn))");
        writer.WriteLine("#else");
        writer.WriteLine("#define CT_NORETURN _Noreturn");
        writer.WriteLine("#endif");
        writer.WriteLine("#if defined(__GNUC__) || defined(__clang__)");
        writer.WriteLine("#define CT_UNUSED __attribute__((unused))");
        writer.WriteLine("#else");
        writer.WriteLine("#define CT_UNUSED");
        writer.WriteLine("#endif");
        writer.WriteLine("#if defined(_MSC_VER)");
        writer.WriteLine("#define CT_INLINE __forceinline");
        writer.WriteLine("#define CT_NOINLINE __declspec(noinline)");
        writer.WriteLine("#define CT_COLD CT_NOINLINE");
        writer.WriteLine("#define CT_UNLIKELY(value) (value)");
        writer.WriteLine("#elif defined(__GNUC__) || defined(__clang__)");
        writer.WriteLine("#define CT_INLINE inline __attribute__((always_inline, unused))");
        writer.WriteLine("#define CT_NOINLINE __attribute__((noinline))");
        writer.WriteLine("#define CT_COLD __attribute__((cold, noinline))");
        writer.WriteLine("#define CT_UNLIKELY(value) __builtin_expect(!!(value), 0)");
        writer.WriteLine("#else");
        writer.WriteLine("#define CT_INLINE inline");
        writer.WriteLine("#define CT_NOINLINE");
        writer.WriteLine("#define CT_COLD");
        writer.WriteLine("#define CT_UNLIKELY(value) (value)");
        writer.WriteLine("#endif");
        writer.WriteLine("#if defined(_MSC_VER)");
        writer.WriteLine("#define CT_FLEXIBLE_ARRAY 1");
        writer.WriteLine("#else");
        writer.WriteLine("#define CT_FLEXIBLE_ARRAY");
        writer.WriteLine("#endif");
        if (_nativeBufferTypes.Count != 0)
        {
            writer.WriteLine("#if defined(_MSC_VER)");
            writer.WriteLine("#define CT_ALLOCA(bytes) _alloca(bytes)");
            writer.WriteLine("#else");
            writer.WriteLine("#define CT_ALLOCA(bytes) __builtin_alloca(bytes)");
            writer.WriteLine("#endif");
        }
        writer.WriteLine();
        EmitAtomicRuntime(writer);
        writer.WriteLine();
        writer.WriteLine("typedef struct ct_vtable ct_vtable;");
        writer.WriteLine("typedef struct ct_type_descriptor ct_type_descriptor;");
        writer.WriteLine("typedef struct ct_interface_entry ct_interface_entry;");
        if (!IsFreestanding)
        {
            writer.WriteLine("typedef struct ct_panic_info { const char* Code; const char* File; int32_t Line; } ct_panic_info;");
            writer.WriteLine("typedef void (*ct_panic_handler)(const ct_panic_info* info, void* context);");
            writer.WriteLine("typedef struct ct_runtime_config { uint32_t Size; ct_panic_handler PanicHandler; void* PanicContext; } ct_runtime_config;");
        }
        else
        {
            writer.WriteLine("static void* ct_runtime_allocate_bridge(size_t size);");
            writer.WriteLine("static void ct_runtime_free_bridge(void* value);");
            writer.WriteLine("static void ct_runtime_panic_bridge(const char* code, const char* file, int32_t line);");
        }
        writer.WriteLine("typedef struct ct_module_descriptor { uint32_t AbiVersion; const char* Name; void (*Initialize)(void); void (*Finalize)(void); } ct_module_descriptor;");
        writer.WriteLine("static void ct_module_init(void);");
        writer.WriteLine("static void ct_module_fini(void);");
        writer.WriteLine("static ct_module_descriptor ct_program_module;");
        writer.WriteLine("typedef struct ct_object { const ct_type_descriptor* Type; ct_atomic_u32 IdentityHash; ct_atomic_u32 RefCount; struct ct_object* ReleaseNext; } ct_object;");
        if (EmitDebugInformation)
        {
            writer.WriteLine("#if defined(_MSC_VER)");
            writer.WriteLine("#define CT_DEBUG_NOINLINE __declspec(noinline)");
            writer.WriteLine("#else");
            writer.WriteLine("#define CT_DEBUG_NOINLINE __attribute__((noinline, used))");
            writer.WriteLine("#endif");
            writer.WriteLine(EmitDebugInstrumentation ? "#define CT_DEBUG_USER_NOINLINE CT_DEBUG_NOINLINE" : "#define CT_DEBUG_USER_NOINLINE");
            writer.WriteLine("static volatile uintptr_t ct_debug_probe_sink;");
            writer.WriteLine("CT_DEBUG_NOINLINE void ct_debug_throw_hook(ct_object* exception, const char* code, const char* file, int line, uint32_t unhandled);");
            writer.WriteLine("CT_DEBUG_NOINLINE void ct_debug_fatal_hook(const char* code, const char* file, int line);");
            if (!EmitDebugInstrumentation)
            {
                writer.WriteLine("CT_DEBUG_NOINLINE void ct_debug_throw_hook(ct_object* exception, const char* code, const char* file, int line, uint32_t unhandled) { ct_debug_probe_sink = (uintptr_t)(void*)exception ^ (uintptr_t)(unsigned int)line ^ (uintptr_t)unhandled; (void)code; (void)file; }");
                writer.WriteLine("CT_DEBUG_NOINLINE void ct_debug_fatal_hook(const char* code, const char* file, int line) { ct_debug_probe_sink = (uintptr_t)(unsigned int)line; (void)code; (void)file; }");
            }
        }
        if (EmitDebugInstrumentation)
        {
            var enabledWords = Math.Max(1, (_debugSites.Count + 31) / 32);
            writer.WriteLine("enum { CT_DEBUG_REASON_SITE = 1u, CT_DEBUG_REASON_THROW = 2u, CT_DEBUG_REASON_FATAL = 3u, CT_DEBUG_REASON_ALLOC = 4u, CT_DEBUG_REASON_RELEASE = 5u, CT_DEBUG_REASON_LEAK = 6u, CT_DEBUG_REASON_STARTUP = 7u };");
            writer.WriteLine("enum { CT_DEBUG_EVENT_THROW = 1u, CT_DEBUG_EVENT_UNHANDLED = 2u, CT_DEBUG_EVENT_FATAL = 4u, CT_DEBUG_EVENT_ALLOC = 8u, CT_DEBUG_EVENT_RELEASE = 16u, CT_DEBUG_EVENT_LEAK = 32u, CT_DEBUG_EVENT_STARTUP = 64u };");
            writer.WriteLine($"typedef struct ct_debug_control_block {{ uint32_t Magic; uint32_t SiteCount; volatile uint32_t SessionActive; volatile uint32_t StartupReleased; volatile uint32_t EventMask; volatile uint32_t StepMode; volatile uint32_t StepDepth; volatile uintptr_t SelectedThread; volatile uintptr_t CurrentThread; volatile uintptr_t CurrentActivation; volatile uint32_t CurrentSite; volatile uint32_t CurrentReason; volatile uintptr_t CurrentObject; volatile uint32_t CurrentValue; volatile uintptr_t CurrentCode; volatile uintptr_t CurrentFile; volatile int32_t CurrentLine; volatile uint32_t Enabled[{enabledWords}]; }} ct_debug_control_block;");
            writer.WriteLine($"ct_debug_control_block ct_debug_control = {{ UINT32_C(0x43544432), UINT32_C({_debugSites.Count}), 0u, 0u, 0u, 0u, 0u, 0u, 0u, 0u, UINT32_MAX, 0u, 0u, 0u, 0u, 0u, 0, {{0}} }};");
            writer.WriteLine("typedef struct ct_debug_runtime_summary_block { uint32_t LiveObjectCount; uint32_t TotalAllocations; uint32_t TotalFinalReleases; uint32_t QuarantineBlocks; uintptr_t QuarantineBytes; uint32_t CurrentSite; } ct_debug_runtime_summary_block;");
            writer.WriteLine("ct_debug_runtime_summary_block ct_debug_runtime_summary;");
            writer.WriteLine("static_assert(offsetof(ct_debug_control_block, SelectedThread) == (sizeof(uintptr_t) == 4u ? 28u : 32u), \"C~ debug control layout mismatch\");");
            writer.WriteLine("static_assert(offsetof(ct_debug_control_block, Enabled) == (sizeof(uintptr_t) == 4u ? 68u : 100u), \"C~ debug bitmap layout mismatch\");");
            writer.WriteLine("static_assert(offsetof(ct_debug_runtime_summary_block, QuarantineBytes) == 16u, \"C~ debug summary layout mismatch\");");
            writer.WriteLine("static ct_atomic_u32 ct_debug_stop_lock = CT_ATOMIC_U32_INIT(0u);");
            writer.WriteLine("typedef struct ct_debug_method_frame { void* State; struct ct_debug_method_frame* Previous; uintptr_t Activation; bool Active; } ct_debug_method_frame;");
            writer.WriteLine("CT_DEBUG_NOINLINE void ct_debug_site(uint32_t site);");
            writer.WriteLine("CT_DEBUG_NOINLINE void ct_debug_keep(void* storage);");
            writer.WriteLine("void ct_debug_method_enter(ct_debug_method_frame* frame);");
            writer.WriteLine("void ct_debug_method_leave(void* value);");
            writer.WriteLine("static void ct_debug_runtime_event(uint32_t reason, uint32_t mask, ct_object* object, uint32_t value, const char* code, const char* file, int32_t line);");
            if (IsEspIdf)
            {
                writer.WriteLine("void ct_debug_startup_probe(void);");
                if (IsQemu)
                    writer.WriteLine("CT_DEBUG_NOINLINE void ct_debug_qemu_ready(void);");
                else
                    writer.WriteLine("void ct_debug_wait_for_client(void);");
            }
            if (EmitDebugObjects)
            {
                writer.WriteLine("static void ct_debug_object_initialized(ct_object* object);");
                writer.WriteLine("static void ct_debug_arc_touch(ct_object* object);");
                writer.WriteLine("static void ct_debug_report_leaks(void);");
            }
        }
        writer.WriteLine("static_assert(sizeof(ct_atomic_u32) == sizeof(uint32_t), \"C~ atomic header fields must remain 32-bit\");");
        writer.WriteLine("static_assert(_Alignof(ct_atomic_u32) == _Alignof(uint32_t), \"C~ atomic header fields must preserve managed-header alignment\");");
        writer.WriteLine("typedef void (*ct_drop_value_fn)(void*);");
        writer.WriteLine("typedef struct ct_cleanup_record { struct ct_cleanup_record* Previous; void* Value; ct_drop_value_fn Drop; bool Active; } ct_cleanup_record;");
        writer.WriteLine("typedef enum ct_runtime_fault_kind { CT_FAULT_NULL, CT_FAULT_BOUNDS, CT_FAULT_DIVIDE, CT_FAULT_CAST, CT_FAULT_OVERFLOW, CT_FAULT_ARGUMENT, CT_FAULT_ARGUMENT_NULL, CT_FAULT_ARGUMENT_OUT_OF_RANGE, CT_FAULT_FORMAT, CT_FAULT_OUT_OF_MEMORY, CT_FAULT_THREAD_STATE, CT_FAULT_SYNCHRONIZATION_LOCK } ct_runtime_fault_kind;");
        writer.WriteLine("CT_NORETURN static void ct_raise_runtime_fault(ct_runtime_fault_kind kind, const char* code, const char* file, int line);");
        if (_usesExceptions)
        {
            writer.WriteLine("typedef struct ct_exception_frame { jmp_buf* Target; struct ct_exception_frame* Previous; ct_cleanup_record* CleanupBoundary; } ct_exception_frame;");
            writer.WriteLine("CT_NORETURN static void ct_unhandled_exception(ct_object* exception);");
            writer.WriteLine("static bool ct_runtime_faults_ready;");
            writer.WriteLine("static void ct_runtime_faults_init(void);");
        }
        writer.WriteLine("typedef struct ct_thread_state {");
        writer.WriteLine("    ct_cleanup_record* CleanupTop;");
        if (_usesExceptions)
        {
            writer.WriteLine("    ct_exception_frame* ExceptionTop;");
            writer.WriteLine("    ct_object* CurrentException;");
            writer.WriteLine("    const char* ExceptionCode;");
            writer.WriteLine("    const char* ExceptionFile;");
            writer.WriteLine("    int32_t ExceptionLine;");
        }
        writer.WriteLine("    ct_object* ReleaseHead;");
        writer.WriteLine("    bool ReleaseDraining;");
        writer.WriteLine("    bool HeapAllocated;");
        if (EmitDebugInstrumentation)
        {
            writer.WriteLine("    uint32_t DebugDepth;");
            writer.WriteLine("    uint32_t DebugCurrentSite;");
            writer.WriteLine("    uintptr_t DebugNextActivation;");
            writer.WriteLine("    ct_debug_method_frame* DebugFrameTop;");
        }
        writer.WriteLine("} ct_thread_state;");
        EmitThreadStorage(writer);
        writer.WriteLine("struct ct_type_descriptor { const char* Name; const ct_type_descriptor* Base; const ct_vtable* VTable; const ct_interface_entry* Interfaces; uint32_t InterfaceCount; uint32_t TypeId; size_t Size; size_t Alignment; bool IsValue; void (*Drop)(ct_object*); };");
        writer.WriteLine("extern const ct_type_descriptor ct_desc_string;");
        writer.WriteLine("typedef struct ct_string { ct_object Object; int32_t Length; uint8_t Data[CT_FLEXIBLE_ARRAY]; } ct_string;");
        if (_usesNativeUtf8)
            writer.WriteLine("typedef struct ct_native_utf8_string { ct_string* Owner; const uint8_t* Data; size_t ByteLength; } ct_native_utf8_string;");
        writer.WriteLine("typedef struct ct_empty_string_storage_type { ct_object Object; int32_t Length; uint8_t Data[1]; } ct_empty_string_storage_type;");
        writer.WriteLine("static const ct_empty_string_storage_type ct_empty_string_storage = { { &ct_desc_string, 0, CT_ATOMIC_U32_INIT(UINT32_MAX), NULL }, 0, { 0 } };");
        writer.WriteLine("static ct_string* const ct_empty_string = (ct_string*)(uintptr_t)(const void*)&ct_empty_string_storage;");
        writer.WriteLine();
        if (!IsFreestanding)
        {
            writer.WriteLine("static ct_panic_handler ct_installed_panic_handler = NULL;");
            writer.WriteLine("static void* ct_installed_panic_context = NULL;");
        }
        writer.WriteLine("CT_NORETURN static void ct_fail(const char* code, const char* file, int line)");
        writer.WriteLine("{");
        if (EmitDebugInformation)
            writer.WriteLine("    ct_debug_fatal_hook(code, file, line);");
        if (IsFreestanding)
        {
            writer.WriteLine("    ct_runtime_panic_bridge(code, file, (int32_t)line);");
            writer.WriteLine("    for (;;) { __asm__ volatile (\"\" ::: \"memory\"); }");
        }
        else
        {
            writer.WriteLine("    ct_panic_info info = { code, file, (int32_t)line };");
            writer.WriteLine("    if (ct_installed_panic_handler != NULL) ct_installed_panic_handler(&info, ct_installed_panic_context);");
            writer.WriteLine("    (void)fprintf(stderr, \"C~ runtime error %s at %s:%d\\n\", code, file, line);");
            writer.WriteLine("    (void)fflush(stderr);");
            writer.WriteLine(PanicTerminationStatement());
        }
        writer.WriteLine("}");
        writer.WriteLine("static CT_COLD CT_NORETURN void ct_null_fail(const char* file, int line) { ct_raise_runtime_fault(CT_FAULT_NULL, \"CTN0001\", file, line); }");
        writer.WriteLine("static CT_INLINE void* ct_require_nonnull(void* value, const char* file, int line) { if (CT_UNLIKELY(value == NULL)) ct_null_fail(file, line); return value; }");
        EmitPlatformAllocation(writer);
        if (HasNativeImports)
        {
            writer.WriteLine("static void ct_native_imports_init(void);");
            writer.WriteLine("static void ct_native_imports_fini(void);");
        }
        EmitThreadRuntime(writer);
        if (EmitDebugInstrumentation)
            EmitInstrumentedDebugRuntime(writer);
        writer.WriteLine("#define ct_cleanup_top (ct_thread_require_attached()->CleanupTop)");
        if (_usesExceptions)
        {
            writer.WriteLine("#define ct_exception_top (ct_thread_require_attached()->ExceptionTop)");
            writer.WriteLine("#define ct_current_exception (ct_thread_require_attached()->CurrentException)");
        }
        writer.WriteLine("static void ct_release_last(ct_object* object, ct_thread_state* state);");
        writer.WriteLine("static CT_INLINE void ct_retain_core(ct_object* object) {" +
            (EmitDebugObjects ? " ct_debug_arc_touch(object);" : string.Empty) +
            " uint32_t count = ct_atomic_load_relaxed(&object->RefCount); for (;;) { if (count == UINT32_MAX) return; if (CT_UNLIKELY(count == 0u || count == UINT32_MAX - 1u)) ct_fail(\"CTM0002\", \"<runtime>\", 0); if (ct_atomic_compare_exchange_relaxed(&object->RefCount, &count, count + 1u)) return; } }");
        writer.WriteLine("static CT_INLINE uint32_t ct_release_decrement(ct_object* object) {" +
            (EmitDebugObjects ? " ct_debug_arc_touch(object);" : string.Empty) +
            " uint32_t count = ct_atomic_load_relaxed(&object->RefCount); for (;;) { if (count == UINT32_MAX) return UINT32_MAX; if (CT_UNLIKELY(count == 0u)) ct_fail(\"CTM0003\", \"<runtime>\", 0); if (ct_atomic_compare_exchange_release(&object->RefCount, &count, count - 1u)) return count; } }");
        writer.WriteLine("static CT_INLINE void ct_retain_fast(ct_object* object) { if (object != NULL) ct_retain_core(object); }");
        writer.WriteLine("static CT_INLINE void ct_release_fast(ct_object* object) { if (object == NULL) return; uint32_t count = ct_release_decrement(object); if (CT_UNLIKELY(count == 1u)) ct_release_last(object, NULL); }");
        writer.WriteLine("void ct_retain(ct_object* object) { (void)ct_thread_require_attached(); ct_retain_fast(object); }");
        writer.WriteLine("void ct_release(ct_object* object) { ct_thread_state* state = ct_thread_require_attached(); if (object == NULL) return; uint32_t count = ct_release_decrement(object); if (count == 1u) ct_release_last(object, state); }");
        writer.WriteLine("static void ct_release_last(ct_object* object, ct_thread_state* state)");
        writer.WriteLine("{");
        writer.WriteLine("    if (state == NULL) state = ct_thread_require_attached();");
        writer.WriteLine("    ct_atomic_acquire_fence();");
        if (EmitDebugObjects)
            writer.WriteLine("    ct_debug_runtime_event(CT_DEBUG_REASON_RELEASE, CT_DEBUG_EVENT_RELEASE, object, 0u, NULL, NULL, 0);");
        writer.WriteLine("    object->ReleaseNext = state->ReleaseHead;");
        writer.WriteLine("    state->ReleaseHead = object;");
        writer.WriteLine("    if (state->ReleaseDraining) return;");
        writer.WriteLine("    state->ReleaseDraining = true;");
        writer.WriteLine("    while (state->ReleaseHead != NULL)");
        writer.WriteLine("    {");
        writer.WriteLine("        ct_object* current = state->ReleaseHead;");
        writer.WriteLine("        state->ReleaseHead = current->ReleaseNext;");

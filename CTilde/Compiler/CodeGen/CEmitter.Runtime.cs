    private void EmitThreadRuntime(CWriter writer)
    {
        if (IsFreestanding)
        {
            writer.WriteLine("enum { CT_RUNTIME_UNINITIALIZED = 0u, CT_RUNTIME_INITIALIZING = 1u, CT_RUNTIME_READY = 2u, CT_RUNTIME_SHUTTING_DOWN = 3u, CT_RUNTIME_STOPPED = 4u };");
